func TestParseModulePath(t *testing.T) {
	tests := []struct {
		name  string
		goMod string
		want  string
	}{
		{"plain", "module example.com/old/module\n\ngo 1.25\n", "example.com/old/module"},
		{"quoted", "// comment\nmodule \"example.com/quoted\"\n", "example.com/quoted"},
		{"trailing comment", "module example.com/old/module // mirror\n", "example.com/old/module"},
		{"indented", "\tmodule example.com/indented\n", "example.com/indented"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := parseModulePath([]byte(tt.goMod))
			if err != nil {
				t.Fatalf("parseModulePath: %v", err)
			}
			if got != tt.want {
				t.Fatalf("parseModulePath = %q, want %q", got, tt.want)
			}
		})
	}
}

