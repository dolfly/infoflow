func TestRewriteFileContentRewritesGeneratedImportsOnly(t *testing.T) {
	const content = `// Code generated by protoc-gen-go. DO NOT EDIT.

package pb

import (
	pb "example.com/old/module/pb"
)

var raw = "\x04\x01Z\x1eexample.com/old/module/pb;pb"
`
	got, changed := rewriteFileContent("gen.pb.go", []byte(content), "example.com/old/module", "github.com/dolfly/infoflow")
	if !changed {
		t.Fatal("rewriteFileContent reported no change for a generated file with a matching import")
	}
	if !strings.Contains(string(got), `pb "github.com/dolfly/infoflow/pb"`) {
		t.Fatalf("generated import not rewritten:\n%s", got)
	}
	if !strings.Contains(string(got), `example.com/old/module/pb;pb`) {
		t.Fatalf("generated descriptor literal must stay byte-identical:\n%s", got)
	}
}

