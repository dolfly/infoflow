func TestCommitMessageNamesOnlyPublishedModulePath(t *testing.T) {
	const newModule = "github.com/dolfly/infoflow"
	msg := commitMessage(newModule)
	for _, needle := range []string{
		newModule,
		"Co-Authored-By: Claude Code <noreply@anthropic.com>",
	} {
		if !strings.Contains(msg, needle) {
			t.Fatalf("commitMessage missing %q:\n%s", needle, msg)
		}
	}
	// The mirror is public: any dotted path other than the published module
	// would name the source module or an internal host.
	for field := range strings.FieldsSeq(msg) {
		field = strings.Trim(field, "`.,;:()")
		if strings.Contains(field, "/") && strings.Contains(field, ".") && !strings.Contains(field, newModule) {
			t.Fatalf("commitMessage names a path other than %s: %q\n%s", newModule, field, msg)
		}
	}
}

func TestCommitMirrorCreatesRootCommit(t *testing.T) {
	dir := newGitRepo(t)
	writeFile(t, dir, "go.mod", "module example.com/old/module\n")
	writeFile(t, dir, "keep.md", "old source\n")
	mustGit(t, dir, "add", ".")
	mustGit(t, dir, "commit", "-q", "-m", "trunk history")
	trunkHead, err := gitOutput(dir, "rev-parse", "HEAD")
	if err != nil {
		t.Fatalf("rev-parse trunk HEAD: %v", err)
	}

	writeFile(t, dir, "go.mod", "module github.com/dolfly/infoflow\n")
	writeFile(t, dir, "keep.md", "mirror content\n")
	commit, err := commitMirror(context.Background(), dir, "mirror root commit")
	if err != nil {
		t.Fatalf("commitMirror: %v", err)
	}
	if commit == "" {
		t.Fatal("commitMirror returned an empty commit")
	}
	if got := readFile(t, dir, "go.mod"); !strings.Contains(got, "github.com/dolfly/infoflow") {
		t.Fatalf("mirror tree not staged: %q", got)
	}
	if got := readFile(t, dir, "keep.md"); got != "mirror content\n" {
		t.Fatalf("mirror tree not staged: %q", got)
	}

	parents, err := gitOutput(dir, "rev-list", "--parents", "-n", "1", commit)
	if err != nil {
		t.Fatalf("rev-list parents: %v", err)
	}
	if strings.Contains(parents, " ") {
		t.Fatalf("mirror commit has parents: %q", parents)
	}
	if count, err := gitOutput(dir, "rev-list", "--count", commit); err != nil || strings.TrimSpace(count) != "1" {
		t.Fatalf("mirror history count = %q, err=%v, want 1", count, err)
	}
	if err := exec.Command("git", "-C", dir, "merge-base", "--is-ancestor", trunkHead, commit).Run(); err == nil {
		t.Fatal("mirror commit still descends from trunk history")
	}
	if status, err := gitOutput(dir, "status", "--porcelain"); err != nil || strings.TrimSpace(status) != "" {
		t.Fatalf("worktree not clean after commitMirror: %q, err=%v", status, err)
	}
}

func newGitRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	mustGit(t, dir, "init", "-q")
	mustGit(t, dir, "config", "user.email", "upstream-push@example.com")
	mustGit(t, dir, "config", "user.name", "upstream-push test")
	return dir
}

func mustGit(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
	}
}

func writeFile(t *testing.T, dir, rel, content string) {
	t.Helper()
	path := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", rel, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", rel, err)
	}
}

func writeExecutable(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o755); err != nil {
		t.Fatalf("write executable %s: %v", path, err)
	}
}

func readFile(t *testing.T, dir, rel string) string {
	t.Helper()
	content, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("read %s: %v", rel, err)
	}
	return string(content)
}
