func TestRewriteWorktreeRewritesTrackedFiles(t *testing.T) {
	dir := newGitRepo(t)
	writeFile(t, dir, "go.mod", "module example.com/old/module\n\ngo 1.25\n")
	writeFile(t, dir, "client.go", "package example\n\nimport \"example.com/old/module/bot\"\n")
	writeFile(t, dir, "docs/README.md", "go get example.com/old/module@v0.1.0\n")
	writeFile(t, dir, "untouched.go", "package example\n")
	writeFile(t, dir, "untracked.md", "example.com/old/module\n")
	mustGit(t, dir, "add", "go.mod", "client.go", "docs/README.md", "untouched.go")
	mustGit(t, dir, "commit", "-q", "-m", "seed")

	changed, err := rewriteWorktree(context.Background(), dir, "example.com/old/module", "github.com/dolfly/infoflow")
	if err != nil {
		t.Fatalf("rewriteWorktree: %v", err)
	}
	want := []string{"client.go", "docs/README.md", "go.mod"}
	if !reflect.DeepEqual(changed, want) {
		t.Fatalf("rewriteWorktree changed %v, want %v", changed, want)
	}
	if got := readFile(t, dir, "go.mod"); !strings.Contains(got, "module github.com/dolfly/infoflow\n") {
		t.Fatalf("go.mod not rewritten: %q", got)
	}
	if got := readFile(t, dir, "untracked.md"); !strings.Contains(got, "example.com/old/module") {
		t.Fatalf("untracked file was rewritten: %q", got)
	}
	if got := readFile(t, dir, "untouched.go"); got != "package example\n" {
		t.Fatalf("unrelated file changed: %q", got)
	}
}

